import { TdxBaseApi } from "./base";

const SETUP_CMD1 = Buffer.from([
  0x0c, 0x02, 0x18, 0x93, 0x00, 0x01, 0x03, 0x00,
  0x03, 0x00, 0x0d, 0x00, 0x01,
]);

const SETUP_CMD2 = Buffer.from([
  0x0c, 0x02, 0x18, 0x94, 0x00, 0x01, 0x03, 0x00,
  0x03, 0x00, 0x0d, 0x00, 0x02,
]);

const SETUP_CMD3 = Buffer.from([
  0x0c, 0x03, 0x18, 0x99, 0x00, 0x01, 0x20, 0x00,
  0x20, 0x00, 0xdb, 0x0f, 0xd5, 0xd0, 0xc9, 0xcc,
  0xd6, 0xa4, 0xa8, 0xaf, 0x00, 0x00, 0x00, 0x8f,
  0xc2, 0x25, 0x40, 0x13, 0x00, 0x00, 0xd5, 0x00,
  0xc9, 0xcc, 0xbd, 0xf0, 0xd7, 0xea, 0x00, 0x00,
  0x00, 0x02,
]);

export async function setupCommands(api: TdxBaseApi): Promise<void> {
  await api.sendRequest(0, SETUP_CMD1);
  await api.sendRequest(0, SETUP_CMD2);
  await api.sendRequest(0, SETUP_CMD3);
}

export { SETUP_CMD1, SETUP_CMD2, SETUP_CMD3 };
